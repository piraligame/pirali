/* PIRALI Beta 1.19 mobile input regression tests. Run: node qa/pirali-beta119-joystick.cjs */
'use strict';
const assert=require('node:assert/strict');
const path=require('node:path'),fs=require('node:fs'),vm=require('node:vm');
const {spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const near=(a,b,why)=>assert.ok(Math.abs(a-b)<1e-6,why+' '+a+' != '+b);
const finger=(identifier,x,y)=>({identifier,clientX:x,clientY:y});
for(const mode of ['play','dev']){
 const folder=path.join(root,'beta119-'+mode);
 const combatPath=path.join(folder,'js/runtime/combat.js');
 const content=fs.readFileSync(combatPath,'utf8');
 const check=spawnSync(process.execPath,['--check',combatPath],{encoding:'utf8'});
 assert.equal(check.status,0,'syntax failed '+check.stderr);
 const cut=content.indexOf('// Keyboard events are owned');
 assert.ok(cut>1000,'combat actions remain loaded after joystick');
 const prefix=content.slice(0,cut);
 const handlers={},resize={};
 const make=()=>({style:{},addEventListener(name,cb){handlers[name]=cb;}});
 const zone=make(),base=make(),knob=make();
 const window={innerWidth:390,innerHeight:820,addEventListener(n,cb){resize[n]=cb;}};
 const scene={window,document:{getElementById(n){return {'joy-zone':zone,'joy-base':base,'joy-knob':knob}[n];}},Math,running:true,P:{dead:false}};
 vm.createContext(scene);
 vm.runInContext(prefix,scene,{timeout:700});
 const joy=vm.runInContext('joy',scene);
 const go=(name,...touches)=>handlers[name]({changedTouches:touches,preventDefault(){}});
 go('touchstart',finger(1,80,690));
 assert.equal(joy.active,true,'touch engages joystick');
 near(joy.bx,81.9,'fixed horizontal position');
 near(joy.by,656,'fixed vertical position');
 assert.equal(base.style.left,'81.89999999999999px'||base.style.left);
 const fixedX=base.style.left,fixedY=base.style.top;
 go('touchmove',finger(1,80,687));near(joy.dy,0,'3px accidental movement filtered');
 go('touchmove',finger(1,80,684));near(joy.dy,-1,'intentional upward movement');
 go('touchmove',finger(1,80,250));near(joy.dy,-1,'long upwards swipe still moves');
 assert.equal(base.style.left,fixedX,'base never follows finger horizontally');
 assert.equal(base.style.top,fixedY,'base never follows finger upwards');
 near(joy.bx,81.9,'base X remains fixed');
 near(joy.by,656,'base Y remains fixed');
 assert.ok(Math.hypot(parseFloat(knob.style.left)-joy.bx,parseFloat(knob.style.top)-joy.by)<=30.000001,
  'knob never leaves visual radius');
 go('touchmove',finger(1,80,260));near(joy.dy,1,'10px reversal after long swipe');
 assert.equal(base.style.top,fixedY,'reverse does not transport ring');
 go('touchmove',finger(1,90,270));near(Math.hypot(joy.dx,joy.dy),1,'diagonal normalized');
 go('touchmove',finger(2,400,300));
 assert.equal(joy.id,1,'second touch cannot steal stick');
 go('touchend',finger(2,400,300));assert.equal(joy.active,true,'second finger release ignored');
 go('touchcancel',finger(1,90,270));assert.equal(joy.active,false,'cancel releases');
 near(joy.dx,0,'cancel clears X');near(joy.dy,0,'cancel clears Y');
 assert.equal(joy.justReleased,true);
 assert.equal(base.style.display,'none');
 go('touchstart',finger(3,80,690));
 window.innerWidth=720;window.innerHeight=1320;resize.resize();
 near(joy.bx,142,'rotation adjusts fixed horizontal position');
 near(joy.by,1060,'rotation adjusts fixed vertical position');
 go('touchend',finger(3,80,690));assert.equal(joy.active,false);
 scene.running=false;go('touchstart',finger(4,80,690));assert.equal(joy.active,false,'no input during pause');
 scene.running=true;scene.P.dead=true;go('touchstart',finger(4,80,690));assert.equal(joy.active,false,'no input while dead');
 const html=fs.readFileSync(path.join(folder,'index.html'),'utf8');
 assert.match(html,/BETA 1\.19 TEST/);
 assert.match(html,/window.PiraliGameVersion='1.19.0-beta.1/);
 assert.match(html,/combat\.js\?v=beta119-anchored/);
 assert.match(html,/css\/style\.css\?v=beta119-anchored/);
 assert.match(html,/window\.PiraliSeasonReleaseEnabled=false/);
 assert.match(html,/stage5-scattered-ammo\.js/,'prior stage 5 ammo fix preserved');
 assert.match(html,/beta118-stage6-weak15/,'prior stage 6 balance preserved');
 assert.match(html,/beta117-cap/,'prior stage scoring preserved');
 const css=fs.readFileSync(path.join(folder,'css/style.css'),'utf8');
 assert.match(css,/#joy-zone\{[^}]*bottom:0;[^}]*height:60%/);
 assert.match(css,/#joy-base\{[^}]*width:96px;height:96px/);
 assert.match(css,/#joy-knob\{[^}]*width:40px;height:40px/);
 const update=fs.readFileSync(path.join(folder,'js/runtime/update.js'),'utf8');
 assert.match(update,/if\(touchDriving\)\{P\.vx=mx\*sp;P\.vy=my\*sp;\}/,'touch movement instantaneous');
 const lifecycle=fs.readFileSync(path.join(folder,'js/platform/mobile-lifecycle.js'),'utf8');
 assert.match(lifecycle,/joy\.engaged=false;joy\.justReleased=true/,'Android background reset preserved');
 console.log('PASS Beta 1.19 '+mode+': fixed base, long swipe, 10px reverse, rotate, multitouch, pause and prior balances');
}
console.log('PASS both variants');
