'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const backup=path.join(process.env.USERPROFILE,'Documents','PiraliFirebaseBackups','rules-live-before-beta152-reset-20261105.json');
const prior=JSON.parse(fs.readFileSync(backup,'utf8').replace(/^\uFEFF/,''));
assert.ok(prior.rules.scores&&prior.rules.pirali_beta_rating,'Missing preservation targets');
assert.ok(!prior.rules.pirali_release_152_rating,'Target path already exists: stop and inspect live rules');
const source=prior.rules.pirali_beta_rating;
const next=JSON.parse(JSON.stringify(source));
const rec=next.$record;
const old='pirali_beta_1_0_s1', season='pirali_release_152_s1';
assert.ok(rec['.validate'].includes(old),'Unexpected current Beta rules season');
rec['.validate']=rec['.validate'].replaceAll(old,season);
rec['.validate']+=" && newData.child('gameVersion').val() === '1.52-beta.1'";
rec.season['.validate']=rec.season['.validate'].replaceAll(old,season);
rec.score['.validate']=rec.score['.validate'].replace('<= 5500','<= 7000');
assert.ok(rec.score['.validate'].includes('<= 7000'),'Score cap update failed');
rec.gameVersion['.validate']="newData.isString() && newData.val() === '1.52-beta.1'";
prior.rules.pirali_release_152_rating=next;
assert.deepEqual(prior.rules.scores,JSON.parse(fs.readFileSync(backup,'utf8').replace(/^\uFEFF/,'')).rules.scores);
assert.deepEqual(prior.rules.pirali_beta_rating,source);
const ruleFile=path.join(root,'firebase','firebase.beta152.rules.json');
const cfgFile=path.join(root,'firebase.beta152.deploy.json');
fs.writeFileSync(ruleFile,JSON.stringify(prior,null,2)+'\n');
fs.writeFileSync(cfgFile,JSON.stringify({database:{rules:'firebase/firebase.beta152.rules.json'}},null,2)+'\n');
console.log('Generated non-destructive Firebase rules: '+ruleFile);
console.log('Preserved /scores and /pirali_beta_rating; new empty /pirali_release_152_rating, limit 7000.');
