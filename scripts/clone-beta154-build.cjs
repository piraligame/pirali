'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const dir=__dirname,src=path.join(dir,'build-beta152-reset-signed.ps1');
const output=path.join(dir,'build-beta154-signed.ps1');
if(fs.existsSync(output))throw Error('Refusing overwrite Beta 1.54 build script');
let s=fs.readFileSync(src,'utf8');
function r(a,b){assert.ok(s.includes(a),'Expected build script token '+a);s=s.replaceAll(a,b);}
r('1.52','1.54');
r('152','154');
r('v22','v23');
r('-NotePropertyValue 22','-NotePropertyValue 23');
r("($gradle -notmatch 'versionCode 21' -and $gradle -notmatch 'versionCode 22')","($gradle -notmatch 'versionCode 22' -and $gradle -notmatch 'versionCode 23')");
r("$gradle=$gradle.Replace('versionCode 21','versionCode 22')","$gradle=$gradle.Replace('versionCode 22','versionCode 23')\n$gradle=$gradle.Replace('versionName \"1.52\"','versionName \"1.54\"')");
r("-or $gradle -notmatch 'versionName \"1.54\"'","-or ($gradle -notmatch 'versionName \"1.52\"' -and $gradle -notmatch 'versionName \"1.54\"')");
r("versionCode='22'","versionCode='23'");
r('versionCode=22','versionCode=23');
r("Write-Output 'PIRALI_BETA154_NEW_SEASON_SIGNED_SUCCESS'","Write-Output 'PIRALI_BETA154_NEW_SEASON_SIGNED_SUCCESS'");
assert.ok(s.includes("PIRALI_Beta_1.54_Reset_Play_v23.aab"));
assert.ok(s.includes("versionName \"1.54\""));
assert.ok(s.includes("versionCode='23'"));
fs.writeFileSync(output,s);
console.log('Created Beta 1.54 Android signed builder for versionCode 23.');
